<script>
(function(){

const chart = document.getElementById("chart-container");
const svg = document.getElementById("lines");
if(!chart || !svg) return;

/* ===== تعامل دکمه‌ها ===== */

chart.querySelectorAll(".mex-node").forEach(node => {

  if(node.classList.contains("mex-branches-anchor")) return;

  node.setAttribute("tabindex","0");
  node.setAttribute("role","button");

  node.addEventListener("click", () => {
    const href = node.getAttribute("data-href");
    if(href){
      window.location.href = href;
    }
  });

  node.addEventListener("keydown", e => {
    if(e.key === "Enter" || e.key === " "){
      e.preventDefault();
      const href = node.getAttribute("data-href");
      if(href){
        window.location.href = href;
      }
    }
  });

  node.addEventListener("touchstart", () => {
    node.classList.add("is-active");
  }, {passive:true});

  node.addEventListener("touchend", () => {
    setTimeout(() => {
      node.classList.remove("is-active");
    }, 180);
  });

  node.addEventListener("touchcancel", () => {
    node.classList.remove("is-active");
  });

});

function isMobile(){
  return window.matchMedia("(max-width:768px)").matches;
}

/* بقیه کدت همین‌طور ادامه پیدا کند */

function clearLines(){
  svg.innerHTML="";
}

function rect(){
  return chart.getBoundingClientRect();
}

function pointTop(el){
  const c = rect();
  const r = el.getBoundingClientRect();
  return {
    x: r.left + r.width/2 - c.left + chart.scrollLeft,
    y: r.top - c.top + chart.scrollTop
  }
}

function pointBottom(el){
  const c = rect();
  const r = el.getBoundingClientRect();
  return {
    x: r.left + r.width/2 - c.left + chart.scrollLeft,
    y: r.bottom - c.top + chart.scrollTop
  }
}

function pointLeftMiddle(el){
  const c = rect();
  const r = el.getBoundingClientRect();
  return {
    x: r.left - c.left + chart.scrollLeft,
    y: r.top + r.height/2 - c.top + chart.scrollTop
  }
}

function line(x1,y1,x2,y2){
  const el=document.createElementNS("http://www.w3.org/2000/svg","line");
  el.setAttribute("x1",x1);
  el.setAttribute("y1",y1);
  el.setAttribute("x2",x2);
  el.setAttribute("y2",y2);
  svg.appendChild(el);
}

function draw(){

clearLines();
if(isMobile()) return;

svg.setAttribute("width",chart.scrollWidth);
svg.setAttribute("height",chart.scrollHeight);

const trustees = document.querySelector("#level-0 .mex-node");
const board = document.querySelector("#level-0-1 .mex-node");
const manager = document.querySelector("#level-1 .mex-node");
const hoze = document.getElementById("hoze-node");

const departments = [...document.querySelectorAll("#level-2 .mex-node")]
  .filter(n=>!n.classList.contains("mex-branches-anchor"));

const branches = [...document.querySelectorAll("#level-3 .mex-node")];

if(!trustees || !board || !manager) return;

/* ===== اتصال عمودی بالا ===== */

const t = pointBottom(trustees);
const bTop = pointTop(board);
const bBottom = pointBottom(board);
const mTop = pointTop(manager);
const mBottom = pointBottom(manager);

line(t.x, t.y, t.x, bTop.y);
line(bBottom.x, bBottom.y, bBottom.x, mTop.y);

/* ===== حوزه مدیرعامل ===== */

if(hoze){

  const offsetX = 280;
  const offsetY = 40;

  const hozeX = mBottom.x + offsetX;
  const hozeY = mBottom.y + offsetY;

  hoze.style.left = (hozeX - hoze.offsetWidth/2) + "px";
  hoze.style.top = (hozeY - hoze.offsetHeight/2) + "px";

  const h = pointLeftMiddle(hoze);

  line(mBottom.x, mBottom.y + 35, h.x, mBottom.y + 35);
}

/* ===== اتصال معاونت‌ها ===== */

if(departments.length){

  const deptPoints = departments.map(pointTop);
  const minX = Math.min(...deptPoints.map(p=>p.x));
  const maxX = Math.max(...deptPoints.map(p=>p.x));
  const minY = Math.min(...deptPoints.map(p=>p.y));

  const busY = Math.min(mBottom.y + 80, minY - 38);

  line(mBottom.x, mBottom.y, mBottom.x, busY);
  line(minX, busY, maxX, busY);
/* عنوان معاونت‌ها روی خط افقی */

const depTitle = document.getElementById("departments-title");
if(depTitle){

  const centerX = (minX + maxX) / 2;

  depTitle.style.left = centerX + "px";
  depTitle.style.top = busY + "px";

}

  departments.forEach(d=>{
    const p = pointTop(d);
    if(p.y > busY){
      line(p.x, busY, p.x, p.y);
    }
  });

/* ===== اتصال شعب ===== */

  if(branches.length){

    const branchPoints = branches.map(pointTop);
    const minBX = Math.min(...branchPoints.map(p=>p.x));
    const maxBX = Math.max(...branchPoints.map(p=>p.x));
    const firstY = Math.min(...branchPoints.map(p=>p.y));

    const branchBusY = firstY - 34;
    const anchor = (minX + maxX)/2;

    line(anchor, busY, anchor, branchBusY);
    line(minBX, branchBusY, maxBX, branchBusY);
/* عنوان شعب روی خط افقی */

const branchTitle = document.getElementById("branches-title");
if(branchTitle){

  const centerBX = (minBX + maxBX) / 2;

  branchTitle.style.left = centerBX + "px";
  branchTitle.style.top = branchBusY + "px";

}

    branches.forEach(b=>{
      const p = pointTop(b);
      line(p.x, branchBusY, p.x, p.y);
    });
  }
}

}

window.addEventListener("load",()=>setTimeout(draw,200));
window.addEventListener("resize",draw);
chart.addEventListener("scroll",()=>requestAnimationFrame(draw));

})();
</script>
