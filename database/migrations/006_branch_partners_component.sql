-- ============================================================================
--  Migration 006 — افزودنِ کامپوننتِ «همکارانِ شعبه» (branch-partners) به صفحه‌ی شعب
-- ----------------------------------------------------------------------------
--  صفحه‌ی homeِ شعب اکنون علاوه بر branch-home، کامپوننتِ branch-partners را هم دارد
--  که اسلایدری از همکارانِ همان شعبه را نشان می‌دهد. این مهاجرت، صفحه‌ی homeِ همه‌ی
--  شعب (به‌جز ستاد مرکزی، branch_id = 1) را به چیدمانِ نهاییِ استاندارد می‌برد:
--      ["header","branch-home","branch-partners","footer"]
--  ستادِ مرکزی دست‌نخورده می‌ماند. اجرای مجدد بی‌خطر است (idempotent).
-- ============================================================================

UPDATE pages
   SET components = '["header","branch-home","branch-partners","footer"]'
 WHERE slug = 'home'
   AND branch_id <> 1;
