-- ============================================================================
--  Migration 003 — اصلاح طولِ ستون news_code و بازسازیِ کدهای خراب
-- ----------------------------------------------------------------------------
--  مشکل:
--    ستونِ `news_code` به‌صورت VARCHAR(10) تعریف شده بود، اما کدِ تولیدی در
--    news-save.php الگوی «NEWS-YYYYMMDD-XXXX» (۱۸ کاراکتر) دارد. در نتیجه
--    MariaDB مقدار را به ۱۰ کاراکترِ نخست («NEWS-20260») بریده و همه‌ی خبرهای
--    جدید کدِ یکسان می‌گرفتند؛ پس همگی به یک پوشه‌ی تصویر
--    (/uploads/news/NEWS-20260/) اشاره می‌کردند و تصویرِ آخرین آپلود روی همه
--    نشان داده می‌شد.
--
--  این مهاجرت:
--    ۱) طول ستون را به VARCHAR(30) افزایش می‌دهد تا کدِ کامل جا شود.
--    ۲) به هر ردیفِ خراب (کدِ بریده‌شده/تکراری/خالی) یک news_code یکتای جدید
--       بر پایه‌ی id می‌دهد تا خبرها دیگر پوشه‌ی تصویرِ مشترک نداشته باشند.
--
--  هشدار درباره‌ی تصاویر:
--    تصویرِ شاخصِ اصلیِ خبرهای خراب قابل بازیابی نیست (همگی فقط یک فایلِ
--    مشترک داشتند). پس از این مهاجرت، آن خبرها «بدون تصویر» نمایش داده
--    می‌شوند و باید تصویر شاخصشان دوباره آپلود شود.
--
--  اجرا:
--    mysql -u USER -p DBNAME < database/migrations/003_news_code_length_fix.sql
-- ============================================================================

SET NAMES utf8mb4;

-- ۱) افزایش طول ستون ---------------------------------------------------------
ALTER TABLE `news`
  MODIFY `news_code` VARCHAR(30) DEFAULT NULL;

-- ۲) دادنِ کدِ یکتای جدید به ردیف‌های خراب -----------------------------------
--    «خراب» یعنی کدی که با الگوی صحیحِ NEWS-YYYYMMDD-NNNN هم‌خوان نیست،
--    یا کدی که بین چند خبر تکراری است. کدِ جدید بر پایه‌ی id ساخته می‌شود تا
--    قطعاً یکتا باشد (NEWS-FIX-<id>).

-- ۲الف) ردیف‌هایی که اصلاً با الگوی صحیح هم‌خوان نیستند (شاملِ «NEWS-20260»)
UPDATE `news`
SET `news_code` = CONCAT('NEWS-FIX-', `id`)
WHERE `news_code` IS NULL
   OR `news_code` = ''
   OR `news_code` NOT REGEXP '^NEWS-[0-9]{8}-[0-9]{4}$';

-- ۲ب) ردیف‌هایی که الگوشان درست است ولی کدشان با ردیفِ دیگری تکراری است
--      (نگهداریِ کوچک‌ترین id با کدِ اصلی، بازنویسیِ بقیه)
UPDATE `news` AS n
JOIN (
    SELECT `news_code`, MIN(`id`) AS keep_id
    FROM `news`
    WHERE `news_code` REGEXP '^NEWS-[0-9]{8}-[0-9]{4}$'
    GROUP BY `news_code`
    HAVING COUNT(*) > 1
) AS dup ON n.`news_code` = dup.`news_code` AND n.`id` <> dup.keep_id
SET n.`news_code` = CONCAT('NEWS-FIX-', n.`id`);

