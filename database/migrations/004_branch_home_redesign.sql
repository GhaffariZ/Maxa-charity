-- ============================================================================
--  Migration 004 — صفحه‌ی اصلیِ اختصاصیِ شعبه (branch-home)
-- ----------------------------------------------------------------------------
--  شعبه‌ها تا پیش از این، صفحه‌ی home‌شان با کامپوننت‌های ["header","heroindex","footer"]
--  ساخته می‌شد که عملاً کپیِ صفحه‌ی اصلیِ ستاد بود. از این پس بدنه‌ی صفحه‌ی شعبه،
--  کامپوننتِ اختصاصیِ «branch-home» است که فقط محتوای همان شعبه (هیرو/کمپین/خبر/دوره)
--  را نشان می‌دهد.
--
--  این مهاجرت، صفحه‌ی homeِ شعبه‌های موجود (به‌جز ستاد مرکزی، branch_id = 1) را به طرح
--  جدید به‌روزرسانی می‌کند. صفحه‌ی اصلیِ ستاد دست‌نخورده می‌ماند.
--
--  نکته: فقط ردیف‌هایی به‌روز می‌شوند که هنوز همان چیدمانِ پیش‌فرضِ قدیمی را دارند؛
--  اگر مدیرِ شعبه‌ای صفحه‌اش را دستی تغییر داده باشد، این مهاجرت آن را بازنویسی نمی‌کند.
-- ============================================================================

UPDATE pages
   SET components = '["header","branch-home","footer"]'
 WHERE slug = 'home'
   AND branch_id <> 1
   AND REPLACE(REPLACE(components, ' ', ''), '\\/', '/') = '["header","heroindex","footer"]';
